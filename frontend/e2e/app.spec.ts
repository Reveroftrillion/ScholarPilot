import {test,expect} from '@playwright/test';
test.skip(!process.env.QA_BASE_URL,'Requires explicitly selected isolated Mock QA server');
test.beforeAll(async({request})=>{
 const response=await request.get('/api/qa-mode');expect(response.ok()).toBeTruthy();
 const qa=await response.json();expect(qa.offline_provider_fixture).toBeFalsy();expect(qa.external_api_calls).toBe(0);
});
test('real library, PDF selection, source navigation and saved reading position',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'나의 서재.'})).toBeVisible();
 await expect(page.locator('.book-card')).toHaveCount(2);
 await page.screenshot({path:'test-results/library.png',fullPage:true});
 await page.locator('.book-title').filter({hasText:'Deep Learning'}).click();
 await expect(page.locator('.react-pdf__Page canvas')).toBeVisible();
 await page.getByRole('button',{name:'\uC0C8 \uB300\uD654',exact:true}).click();
 await page.getByRole('button',{name:'목차',exact:true}).click();
 await expect(page.locator('.toc')).toBeVisible();
 await page.getByLabel('페이지 번호').fill('45');
 await expect(page.locator('.react-pdf__Page__textContent')).toBeVisible();
 await page.waitForTimeout(700);
 const text=await page.locator('.react-pdf__Page__textContent').innerText();
 expect(text.length).toBeGreaterThan(20);
 await page.locator('.react-pdf__Page__textContent').evaluate(el=>{
   const span=Array.from(el.querySelectorAll('span')).find(s=>(s.textContent?.length||0)>20);
   if(!span)throw new Error('No text span');
   const range=document.createRange();range.selectNodeContents(span);const sel=window.getSelection()!;sel.removeAllRanges();sel.addRange(range);
   el.dispatchEvent(new PointerEvent('pointerup',{bubbles:true}));
 });
 await expect(page.locator('.selection-card')).toBeVisible();
 await page.getByRole('button',{name:'쉽게 설명',exact:true}).click();
 await expect(page.locator('.chat-turn')).not.toHaveCount(0);
 await expect(page.locator('.sources')).toBeVisible();
 await expect(page.locator('.quiz-card')).toBeVisible();
 const radios=page.locator('.quiz-card input[type=radio]');
 if(await radios.count())await radios.first().check();
 else await page.getByLabel('진단 답안').fill('probability');
 await page.getByRole('button',{name:'답안 제출',exact:true}).click();
 await expect(page.locator('.evaluation').last()).toBeVisible();
 await page.getByRole('button',{name:'실행 로그',exact:true}).click();
 await expect(page.locator('.trace-run').last()).toContainText('search_textbook');
 await expect(page.locator('.trace-run').first()).toContainText('evaluate_answer');
 await page.screenshot({path:'test-results/reader.png',fullPage:true});
 await page.getByRole('button',{name:'원문 검색',exact:true}).click();
 await page.getByLabel('원문 검색어').fill('Bayes');
 await page.getByRole('button',{name:'검색',exact:true}).click();
 await expect(page.locator('.search-result').first()).toBeVisible();
 await page.locator('.search-result').first().click();
 const position=await page.getByLabel('페이지 번호').inputValue();
 await page.getByRole('button',{name:'서재로',exact:true}).click();
 await page.reload();
 await page.locator('.book-title').filter({hasText:'Deep Learning'}).click();
 await expect(page.getByLabel('페이지 번호')).toHaveValue(position);
 expect(errors).toEqual([]);
});
